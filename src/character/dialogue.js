/**
 * Shuffle Bag (不重复抽牌包) 机制
 * @type {Record<string, string[]>}
 */
const shuffleBags = {};

/**
 * 从列表中不重复抽取，直到列表全部抽完后才自动重新洗牌
 * @param {string[]} list
 * @param {string} key
 */
function pickWithoutRepeat(list, key = "default") {
  if (!list?.length) return "……";
  if (!shuffleBags[key] || shuffleBags[key].length === 0) {
    // 重新创建洗牌包（Fisher-Yates 随机打乱）
    const bag = [...list];
    for (let i = bag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [bag[i], bag[j]] = [bag[j], bag[i]];
    }
    shuffleBags[key] = bag;
  }
  return shuffleBags[key].pop();
}

export function timeBucket(date = new Date()) {
  const h = date.getHours();
  if (h >= 5 && h < 11) return "morning";
  if (h >= 11 && h < 14) return "noon";
  if (h >= 14 && h < 17) return "afternoon";
  if (h >= 17 && h < 21) return "evening";
  if (h >= 21 && h < 24) return "night";
  return "lateNight";
}

/**
 * @param {string} scene
 * @param {{ affinity?: number, forceTime?: boolean }} [opts]
 */
export function speak(scene, opts = {}) {
  const affinity = opts.affinity ?? 0;
  const rank = getAffinityRank(affinity);

  let targetScene = scene;
  let pool = LINES[targetScene];
  if (!pool && opts.forceTime) {
    targetScene = timeBucket();
    pool = LINES[targetScene];
  }
  if (!pool) {
    targetScene = "talk";
    pool = LINES.talk;
  }

  let text = pickWithoutRepeat(pool, targetScene);

  if (rank.value >= 60 && Math.random() < 0.25 && ["tap", "talk", "praise"].includes(scene)) {
    const warm = pickWithoutRepeat(WARM_SUFFIXES, "warm_suffix");
    text = `${text} ${warm}`;
  }

  return {
    scene,
    text,
    speaker: "天之川沙夜",
    rankTitle: rank.title,
  };
}

